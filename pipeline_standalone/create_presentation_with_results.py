import os
import tifffile
import numpy as np
import matplotlib.pyplot as plt
import pandas as pd
from pptx import Presentation
from pptx.util import Inches, Pt

def generate_snapshots():
    print("Generating snapshots from volume data...")
    # 1. Raw volume MIP
    raw_path = r"..\data_046\F0046_multichannel_cmle_ch03.tif"
    if os.path.exists(raw_path):
        vol = tifffile.imread(raw_path)
        mip = np.max(vol, axis=0)
        plt.figure(figsize=(5,5))
        plt.imshow(mip, cmap='gray')
        plt.axis('off')
        plt.savefig("raw_mip.png", bbox_inches='tight', pad_inches=0, transparent=True)
        plt.close()
        
    # 2. Neurite mask MIP (blended with raw)
    neurite_path = r"..\NEWFP_output\F0046_multichannel_cmle_ch03\neurite_mask.tif"
    if os.path.exists(neurite_path) and os.path.exists(raw_path):
        mask_vol = tifffile.imread(neurite_path)
        raw_vol = tifffile.imread(raw_path)
        mask_mip = np.max(mask_vol, axis=0)
        raw_mip = np.max(raw_vol, axis=0)
        
        plt.figure(figsize=(5,5))
        plt.imshow(raw_mip, cmap='gray')
        plt.imshow(mask_mip, cmap='Reds', alpha=0.5) # Overlay in red with transparency
        plt.axis('off')
        plt.savefig("neurite_mip.png", bbox_inches='tight', pad_inches=0, transparent=True)
        plt.close()
        
    # 3. Soma mask MIP
    soma_path = r"..\NEWFP_output\F0046_multichannel_cmle_ch03\soma_labels.tif"
    if os.path.exists(soma_path):
        vol = tifffile.imread(soma_path)
        mip = np.max(vol, axis=0)
        plt.figure(figsize=(5,5))
        plt.imshow(mip, cmap='magma')
        plt.axis('off')
        plt.savefig("soma_mip.png", bbox_inches='tight', pad_inches=0, transparent=True)
        plt.close()
        
    # 4. SWC scatter
    swc_path = r"..\NEWFP_output\F0046_multichannel_cmle_ch03\skeletons_smooth.swc"
    if os.path.exists(swc_path):
        try:
            df = pd.read_csv(swc_path, sep=r'\s+', comment='#', header=None, names=['id', 'type', 'x', 'y', 'z', 'r', 'pid'])
            plt.figure(figsize=(5,5))
            # Convert physical x,y back to pixels for aspect matching if necessary, 
            # but since x and y have the same scale (0.1102), plotting them directly works.
            plt.scatter(df['x'], df['y'], s=0.01, c='red')
            plt.axis('off')
            plt.gca().set_aspect('equal', adjustable='box')
            plt.gca().invert_yaxis()
            plt.savefig("skeleton_mip.png", bbox_inches='tight', pad_inches=0, transparent=True)
            plt.close()
        except Exception as e:
            print("Could not plot SWC:", e)
            
    print("Snapshots generated.")

def create_presentation(output_path):
    prs = Presentation()
    
    # 1. Title Slide
    title_slide_layout = prs.slide_layouts[0]
    slide = prs.slides.add_slide(title_slide_layout)
    title = slide.shapes.title
    subtitle = slide.placeholders[1]
    title.text = "GPU-Accelerated 3D Neurite Detection Pipeline"
    subtitle.text = "Automated Skeletonization and Proofreading\nGenerated by Samik Banerjee's Pipeline"
    
    # 2. Pipeline Overview
    bullet_slide_layout = prs.slide_layouts[1]
    slide = prs.slides.add_slide(bullet_slide_layout)
    shapes = slide.shapes
    title_shape = shapes.title
    body_shape = shapes.placeholders[1]
    title_shape.text = "Pipeline Overview"
    tf = body_shape.text_frame
    tf.text = "An end-to-end processing pipeline for 3D volume imaging:"
    for txt in ["1. GPU Neurite Detection: Isolate vessel-like structures.",
                "2. Soma Detection: Mask out dense cell bodies.",
                "3. SWC Skeletonization: Multi-threaded graph extraction.",
                "4. Visualization: Interactive 3D rendering with Napari."]:
        p = tf.add_paragraph()
        p.text = txt
        p.level = 1
        
    if os.path.exists("raw_mip.png"):
        slide.shapes.add_picture("raw_mip.png", Inches(5.5), Inches(2.0), height=Inches(4.5))
        
    # 3. Step 1: Neurite Detection
    slide = prs.slides.add_slide(bullet_slide_layout)
    shapes = slide.shapes
    title_shape = shapes.title
    body_shape = shapes.placeholders[1]
    title_shape.text = "Step 1: Neurite Detection"
    tf = body_shape.text_frame
    tf.text = "Script: process_neurites.py"
    for txt in ["Applies a 3D Frangi Vesselness Filter.",
                "GPU-accelerated via CuPy for ultra-fast processing.",
                "Utilizes chunk-based memory management.",
                "Outputs: neurite_mask.tif"]:
        p = tf.add_paragraph()
        p.text = txt
        p.level = 1
        
    if os.path.exists("neurite_mip.png"):
        slide.shapes.add_picture("neurite_mip.png", Inches(5.5), Inches(2.0), height=Inches(4.5))
        
    # 4. Step 2: Soma Detection
    slide = prs.slides.add_slide(bullet_slide_layout)
    shapes = slide.shapes
    title_shape = shapes.title
    body_shape = shapes.placeholders[1]
    title_shape.text = "Step 2: Soma Detection"
    tf = body_shape.text_frame
    tf.text = "Script: detect_somas.py"
    for txt in ["Isolates large spherical cell bodies (somas).",
                "GPU-accelerated morphological operations.",
                "Separates dense cell body clumps from delicate branches.",
                "Outputs: soma_labels.tif"]:
        p = tf.add_paragraph()
        p.text = txt
        p.level = 1
        
    if os.path.exists("soma_mip.png"):
        slide.shapes.add_picture("soma_mip.png", Inches(5.5), Inches(2.0), height=Inches(4.5))
        
    # 5. Step 3: Skeletonization
    slide = prs.slides.add_slide(bullet_slide_layout)
    shapes = slide.shapes
    title_shape = shapes.title
    body_shape = shapes.placeholders[1]
    title_shape.text = "Step 3: Skeletonization & Graph Extraction"
    tf = body_shape.text_frame
    tf.text = "Script: skeletonize_only.py"
    for txt in ["Masks out soma regions to isolate pure neurite paths.",
                "Multi-threaded CPU skeletonization and graph extraction.",
                "Filters isolated speckles and small terminal twigs.",
                "Robust spline smoothing with coordinate downsampling.",
                "Outputs: skeletons_smooth.swc"]:
        p = tf.add_paragraph()
        p.text = txt
        p.level = 1
        
    if os.path.exists("skeleton_mip.png"):
        slide.shapes.add_picture("skeleton_mip.png", Inches(5.5), Inches(2.0), height=Inches(4.5))
        
    # 6. Step 4: 3D Visualization
